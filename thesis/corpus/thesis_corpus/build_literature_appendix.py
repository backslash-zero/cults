"""Build the thesis_v2 appendix listing the approved literature corpus as ranked lists.

The ranking (discipline, rank within discipline, citations, score) comes from the
OpenAlex results file written by scripts/fetch_openalex_corpus.py; the approved
documents come from metadata/literature.csv. Approved documents that are not in
the ranked lists were added by hand and are listed separately.

    python -m thesis_corpus.build_literature_appendix
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

CORPUS = Path(__file__).resolve().parents[1]
RESULTS = CORPUS / "literature" / "openalex_search_results.txt"
APPROVED = CORPUS / "metadata" / "literature.csv"
OUT = CORPUS.parents[1] / "thesis_v2" / "04_Appendix" / "literature_corpus.tex"

ENTRY = re.compile(r"^(\d+)\. (.*) \((\d{4}|n\.d\.)\) — (.*)$")
STATS = re.compile(r"cited_by=(\d+)\s+channels=(\d+)\s+score=([\d.]+)")


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def parse_ranked(text: str) -> list[dict]:
    """Ranked entries from the BOOKS and ARTICLES sections (the excluded list after them is ignored)."""
    rows, category, discipline = [], None, None
    for line in text.splitlines():
        if line.startswith("BOOKS"):
            category = "book"
            continue
        if line.startswith("ARTICLES"):
            category = "article"
            continue
        if line.startswith("EXCLUDED"):
            break
        m = re.match(r"^-- (.*) \(\d+\) --$", line)
        if m:
            discipline = m.group(1)
            continue
        m = ENTRY.match(line)
        if m and category:
            rows.append({"category": category, "discipline": discipline, "rank": int(m.group(1)),
                         "title": m.group(2), "year": m.group(3), "authors": m.group(4)})
            continue
        m = STATS.search(line)
        if m and rows and "cited_by" not in rows[-1]:
            rows[-1].update(cited_by=int(m.group(1)), channels=int(m.group(2)), score=float(m.group(3)))
    return rows


def tex(s: str) -> str:
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return s


def table(rows: list[dict], caption: str, label: str) -> str:
    head = r"Discipline & Rank & Title & Authors & Year & Citations \\"
    out = [r"{\scriptsize", r"\renewcommand{\arraystretch}{1.25}",
           r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.17\textwidth}r>{\raggedright\arraybackslash}p{0.36\textwidth}>{\raggedright\arraybackslash}p{0.2\textwidth}rr@{}}",
           rf"\caption{{{caption}}}\label{{{label}}} \\", r"\toprule", head, r"\midrule", r"\endfirsthead",
           r"\toprule", head, r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"]
    for r in rows:
        out.append(f"{tex(r['discipline'])} & {r['rank']} & {tex(r['title'])} & {tex(r['authors'])} & {r['year']} & {r['cited_by']} \\\\")
    out += [r"\end{longtable}", "}"]
    return "\n".join(out)


def build() -> str:
    ranked = parse_ranked(RESULTS.read_text(encoding="utf-8"))
    approved = list(csv.DictReader(APPROVED.open(encoding="utf-8")))
    # One-to-one: an exact title-and-year match first, then a title-prefix match with the same year;
    # each ranked entry is claimed at most once. Anything left was added by hand.
    claimed, match = set(), {}
    for exact in (True, False):
        for i, a in enumerate(approved):
            if i in match:
                continue
            n = norm(a["title"])
            for j, r in enumerate(ranked):
                k = norm(r["title"])
                same = k == n if exact else min(len(k), len(n)) >= 20 and (k.startswith(n) or n.startswith(k))
                if j not in claimed and same and r["year"] == a["year"]:
                    claimed.add(j)
                    match[i] = r
                    break
    kept = [match[i] for i in sorted(match)]
    by_hand = [a for i, a in enumerate(approved) if i not in match]
    key = lambda r: (r["discipline"], r["rank"])
    books = sorted((r for r in kept if r["category"] == "book"), key=key)
    articles = sorted((r for r in kept if r["category"] == "article"), key=key)
    parts = [
        "% Generated by thesis/corpus/thesis_corpus/build_literature_appendix.py from literature/openalex_search_results.txt"
        " and metadata/literature.csv; do not edit by hand",
        r"\chapter{Literature Corpus}", r"\label{app:literature}", "",
        r"\section{Ranked books and book chapters}", r"\label{sec:ranked_books}", "",
        table(books, f"The {len(books)} approved books and book chapters, by discipline and rank within discipline",
              "tab:ranked_books"), "",
        r"\section{Ranked articles}", r"\label{sec:ranked_articles}", "",
        table(articles, f"The {len(articles)} approved journal articles, by discipline and rank within discipline",
              "tab:ranked_articles"), "",
    ]
    if by_hand:
        parts += [r"\section{Approved outside the ranked lists}", r"\label{sec:literature_by_hand}", "",
                  r"{\scriptsize", r"\begin{itemize}"]
        parts += [r"\item " + ", ".join(tex(x) for x in (a["title"], a["authors"], a["year"]) if x.strip()) for a in by_hand]
        parts += [r"\end{itemize}", "}", ""]
    return "\n".join(parts)


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")
